-- Give stock back when an order is cancelled (and take it again if reinstated).
create or replace function public.sync_stock_on_status() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'cancelled' and old.status <> 'cancelled' then
    update public.products p set stock_qty = p.stock_qty + oi.quantity
      from public.order_items oi where oi.order_id = new.id and oi.product_id = p.id;
  elsif old.status = 'cancelled' and new.status <> 'cancelled' then
    update public.products p set stock_qty = greatest(p.stock_qty - oi.quantity, 0)
      from public.order_items oi where oi.order_id = new.id and oi.product_id = p.id;
  end if;
  return new;
end $$;
drop trigger if exists trg_orders_stock on public.orders;
create trigger trg_orders_stock after update of status on public.orders
  for each row execute function public.sync_stock_on_status();

