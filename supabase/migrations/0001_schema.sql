-- ---------------------------------------------------------------------
-- RPC: place_order — prices and stock are decided here, never by the browser
-- ---------------------------------------------------------------------
create or replace function public.place_order(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  cust        jsonb := p -> 'customer';
  item        jsonb;
  prod        public.products%rowtype;
  qty         int;
  v_subtotal  numeric(10,2) := 0;
  v_fee       numeric(10,2);
  v_tax       numeric(10,2);
  v_free_over numeric(10,2);
  v_tax_rate  numeric := 0;
  v_method    text := coalesce(p ->> 'payment_method', 'mpesa');
  v_has_rx    boolean := false;
  v_rx_path   text := nullif(p ->> 'prescription_path', '');
  v_order     public.orders%rowtype;
  v_lines     jsonb := '[]'::jsonb;
begin
  if cust is null or length(trim(coalesce(cust ->> 'name', ''))) = 0
     or length(trim(coalesce(cust ->> 'phone', ''))) < 9
     or length(trim(coalesce(cust ->> 'address', ''))) = 0 then
    raise exception 'Name, phone and delivery address are required';
  end if;
  if v_method not in ('mpesa', 'cash_on_delivery') then
    raise exception 'Unsupported payment method';
  end if;
  if jsonb_typeof(p -> 'items') is distinct from 'array' or jsonb_array_length(p -> 'items') = 0 then
    raise exception 'Your cart is empty';
  end if;

  -- lock product rows in a stable order to avoid deadlocks
  for item in select value from jsonb_array_elements(p -> 'items') order by (value ->> 'product_id')::bigint loop
    qty := (item ->> 'quantity')::int;
    if qty is null or qty < 1 or qty > 50 then raise exception 'Invalid quantity'; end if;
    select * into prod from public.products where id = (item ->> 'product_id')::bigint and is_active for update;
    if not found then raise exception 'A product in your cart is no longer available'; end if;
    if prod.stock_qty < qty then
      raise exception 'Only % of "%" left in stock', prod.stock_qty, prod.name;
    end if;
    v_subtotal := v_subtotal + prod.price * qty;
    v_has_rx := v_has_rx or prod.requires_prescription;
    v_lines := v_lines || jsonb_build_array(jsonb_build_object('product', to_jsonb(prod), 'qty', qty));
  end loop;

  if v_has_rx and v_rx_path is null then
    raise exception 'A prescription must be uploaded for prescription-only medicines';
  end if;

  select coalesce((value #>> '{}')::numeric, 0) into v_fee from public.site_settings where key = 'delivery_fee';
  select coalesce((value #>> '{}')::numeric, 0) into v_free_over from public.site_settings where key = 'free_delivery_threshold';
  select coalesce((value #>> '{}')::numeric, 0) into v_tax_rate from public.site_settings where key = 'tax_rate';
  v_fee := coalesce(v_fee, 0);
  if v_free_over is not null and v_free_over > 0 and v_subtotal >= v_free_over then v_fee := 0; end if;
  v_tax := round(v_subtotal * coalesce(v_tax_rate, 0) / 100, 2);

  insert into public.orders (user_id, customer_name, email, phone, address, city, delivery_notes,
                             subtotal, delivery_fee, tax, total, status, payment_method, has_rx_items, prescription_path)
  values (auth.uid(), trim(cust ->> 'name'), nullif(trim(coalesce(cust ->> 'email', '')), ''), trim(cust ->> 'phone'),
          trim(cust ->> 'address'), nullif(trim(coalesce(cust ->> 'city', '')), ''), nullif(trim(coalesce(cust ->> 'notes', '')), ''),
          v_subtotal, v_fee, v_tax, v_subtotal + v_fee + v_tax,
          case when v_has_rx then 'prescription_review' else 'pending' end,
          v_method, v_has_rx, v_rx_path)
  returning * into v_order;

  for item in select value from jsonb_array_elements(v_lines) loop
    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity, requires_prescription)
    values (v_order.id, (item #>> '{product,id}')::bigint, item #>> '{product,name}',
            (item #>> '{product,price}')::numeric, (item ->> 'qty')::int,
            (item #>> '{product,requires_prescription}')::boolean);
    update public.products set stock_qty = stock_qty - (item ->> 'qty')::int
      where id = (item #>> '{product,id}')::bigint;
  end loop;

  return jsonb_build_object('order_id', v_order.id, 'order_number', v_order.order_number,
                            'total', v_order.total, 'status', v_order.status, 'has_rx_items', v_has_rx);
end $$;

-- Polling endpoint for the checkout page; the unguessable order uuid is the capability.
create or replace function public.order_payment_status(p_order_id uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'order_number', o.order_number, 'status', o.status, 'payment_status', o.payment_status, 'total', o.total,
    'mpesa_receipt', (select mpesa_receipt from public.payments where order_id = o.id order by id desc limit 1),
    'result_desc',   (select result_desc   from public.payments where order_id = o.id order by id desc limit 1))
  from public.orders o where o.id = p_order_id;
$$;

-- Guest order tracking: order number + the phone used at checkout.
create or replace function public.track_order(p_order_number text, p_phone text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  o public.orders%rowtype;
  digits text := right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 9);
begin
  select * into o from public.orders where upper(order_number) = upper(trim(p_order_number));
  if not found or length(digits) < 9 or right(regexp_replace(o.phone, '\D', '', 'g'), 9) <> digits then
    return null;
  end if;
  return jsonb_build_object(
    'order_number', o.order_number, 'status', o.status, 'payment_status', o.payment_status,
    'payment_method', o.payment_method, 'subtotal', o.subtotal, 'delivery_fee', o.delivery_fee,
    'tax', o.tax, 'total', o.total, 'created_at', o.created_at,
    'items', (select coalesce(jsonb_agg(jsonb_build_object('name', product_name, 'quantity', quantity, 'unit_price', unit_price)), '[]'::jsonb)
              from public.order_items where order_id = o.id));
end $$;

-- Admin dashboard numbers in one round-trip
create or replace function public.admin_dashboard_stats() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Not authorised'; end if;
  return jsonb_build_object(
    'products',        (select count(*) from public.products),
    'active_products', (select count(*) from public.products where is_active),
    'low_stock',       (select count(*) from public.products where is_active and stock_qty <= 10),
    'customers',       (select count(*) from public.profiles where role = 'customer'),
    'orders',          (select count(*) from public.orders),
    'open_orders',     (select count(*) from public.orders where status in ('pending', 'prescription_review', 'confirmed', 'processing', 'out_for_delivery')),
    'rx_waiting',      (select count(*) from public.orders where status = 'prescription_review'),
    'unread_messages', (select count(*) from public.contact_messages where status = 'new'),
    'revenue',         (select coalesce(sum(total), 0) from public.orders where payment_status = 'paid'),
    'revenue_30d',     (select coalesce(sum(total), 0) from public.orders where payment_status = 'paid' and created_at > now() - interval '30 days'),
    'by_status',       (select coalesce(jsonb_object_agg(status, n), '{}'::jsonb) from (select status, count(*) n from public.orders group by status) s));
end $$;

